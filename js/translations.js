// Language switcher functionality
class LanguageSwitcher {
    constructor() {
        this.currentLang = localStorage.getItem('language') || 'pl';
        this.init();
    }
    
    init() {
        // Apply saved language on page load
        this.applyLanguage(this.currentLang);
        
        // Add event listeners to language switcher
        document.addEventListener('DOMContentLoaded', () => {
            // Desktop select dropdown
            const langSelect = document.getElementById('lang-select');
            if (langSelect) {
                // Set initial value based on current language
                langSelect.value = this.currentLang;
                
                // Add change event listener
                langSelect.addEventListener('change', (e) => {
                    const newLang = e.target.value;
                    this.switchLanguage(newLang);
                });
            }
            
            // Mobile select dropdown
            const langSelectMobile = document.getElementById('lang-select-mobile');
            if (langSelectMobile) {
                // Set initial value based on current language
                langSelectMobile.value = this.currentLang;
                
                // Add change event listener
                langSelectMobile.addEventListener('change', (e) => {
                    const newLang = e.target.value;
                    this.switchLanguage(newLang);
                });
            }
        });
    }
    
    switchLanguage(lang) {
        if (lang !== this.currentLang) {
            this.currentLang = lang;
            localStorage.setItem('language', lang);
            this.applyLanguage(lang);
        }
    }
    
    applyLanguage(lang) {
        const elements = document.querySelectorAll('[data-i18n]');
        const questionElement = document.querySelector('.news-opening-question');
        let shouldAnimate = false;
        
        elements.forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                let text = translations[lang][key];
                
                // Jeśli to element pytania, zaktualizuj tekst, ale animacja go zastąpi
                if (element === questionElement && key === 'news.opening.question') {
                    shouldAnimate = true;
                    // Zaktualizuj tekst w tle (animacja go zastąpi)
                    element.textContent = text;
                } else if (element.classList.contains('news-opening-answer')) {
                    // Dla news-opening-answer używamy textContent - tekst płynnie się układa bez wymuszonych łamań
                    element.textContent = text;
                } else if (element.classList.contains('news-intro-text')) {
                    // Dla news-intro-text używamy textContent - tekst płynnie się układa bez wymuszonych łamań
                    element.textContent = text;
                } else if (element.classList.contains('news-intro-title')) {
                    // Dla news-intro-title zaktualizuj tylko span wewnątrz (zachowaj obrazek)
                    const span = element.querySelector('span');
                    if (span) {
                        span.textContent = text;
                    } else {
                        element.textContent = text;
                    }
                } else {
                    element.textContent = text;
                }
            }
        });
        
        // Update HTML lang attribute
        document.documentElement.lang = lang;
        
        // Update desktop select value
        const langSelect = document.getElementById('lang-select');
        if (langSelect) {
            langSelect.value = lang;
        }
        
        // Update mobile select value
        const langSelectMobile = document.getElementById('lang-select-mobile');
        if (langSelectMobile) {
            langSelectMobile.value = lang;
        }
        
        // Jeśli to pytanie, zresetuj flagę animacji i uruchom ponownie
        if (shouldAnimate && questionElement) {
            // Zresetuj flagę animacji, aby można było uruchomić ponownie
            questionElement.dataset.animated = 'false';
            // Uruchom animację ponownie (jeśli sekcja jest widoczna)
            if (typeof window.ssTypingAnimation === 'function') {
                setTimeout(() => {
                    window.ssTypingAnimation();
                }, 100);
            }
        }
    }
}

